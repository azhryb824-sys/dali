import fs from "node:fs";
import path from "node:path";
import ts from "typescript";

const appFiles = [];
const excludedLibraryFiles = new Set([
  "lib/arabic-money.ts",
  "lib/brand-identity-pdf.ts",
  "lib/email-delivery.ts",
  "lib/pdf-generator.ts",
  "lib/workforce-contract-clauses.ts",
]);
function walk(directory, extension) {
  for (const entry of fs.readdirSync(directory, { withFileTypes: true })) {
    const target = path.join(directory, entry.name);
    if (entry.isDirectory()) walk(target, extension);
    else if (entry.name.endsWith(extension) && !excludedLibraryFiles.has(target) && !entry.name.startsWith("i18n")) appFiles.push(target);
  }
}
walk("app", ".tsx");
walk("lib", ".ts");

function normalize(value) {
  return value.replace(/\s+/g, " ").trim();
}

function addLocatedValue(target, rawValue, file) {
  const value = normalize(rawValue);
  if (!/[ء-ي]/.test(value) || value.length < 2 || value.length > 6000) return;
  const files = target.get(value) || new Set();
  files.add(file);
  target.set(value, files);
}

const visibleStrings = new Map();
const visibleTemplates = new Map();
for (const file of appFiles) {
  const source = fs.readFileSync(file, "utf8");
  const tree = ts.createSourceFile(file, source, ts.ScriptTarget.Latest, true, file.endsWith(".tsx") ? ts.ScriptKind.TSX : ts.ScriptKind.TS);
  const visit = (node) => {
    if (ts.isJsxText(node) || ts.isStringLiteral(node) || ts.isNoSubstitutionTemplateLiteral(node)) {
      addLocatedValue(visibleStrings, node.text, file);
    } else if (ts.isTemplateExpression(node)) {
      let value = node.head.text;
      node.templateSpans.forEach((span, index) => { value += `{{${index}}}${span.literal.text}`; });
      addLocatedValue(visibleTemplates, value, file);
    }
    ts.forEachChild(node, visit);
  };
  visit(tree);
}

const runtimeValues = [...visibleStrings.keys()].sort((a, b) => a.localeCompare(b, "ar"));
const runtimeOutput = `// Generated by scripts/audit-translations.mjs. Do not edit manually.\nexport const authoredUiStrings = new Set<string>(${JSON.stringify(runtimeValues, null, 2)});\n`;
if (process.argv.includes("--write-runtime-catalog")) {
  fs.writeFileSync("lib/i18n-authored-strings.ts", runtimeOutput);
} else if (!fs.existsSync("lib/i18n-authored-strings.ts") || fs.readFileSync("lib/i18n-authored-strings.ts", "utf8") !== runtimeOutput) {
  console.error("Runtime translation catalog is stale. Run npm run i18n:generate.");
  process.exitCode = 1;
}

const catalogFiles = [
  "lib/i18n.ts",
  "lib/i18n-public-catalog.ts",
  "lib/i18n-admin-catalog.ts",
  "lib/i18n-generated-catalog.ts",
].filter(fs.existsSync);
const catalogTranslations = new Map();
for (const file of catalogFiles) {
  const source = fs.readFileSync(file, "utf8");
  const tree = ts.createSourceFile(file, source, ts.ScriptTarget.Latest, true, ts.ScriptKind.TS);
  const visit = (node) => {
    if (ts.isPropertyAssignment(node) && ts.isStringLiteral(node.name) && /[ء-ي]/.test(node.name.text) && ts.isObjectLiteralExpression(node.initializer)) {
      const entry = catalogTranslations.get(node.name.text) || {};
      for (const property of node.initializer.properties) {
        if (!ts.isPropertyAssignment(property)) continue;
        const name = ts.isIdentifier(property.name) || ts.isStringLiteral(property.name) ? property.name.text : "";
        if ((name === "en" || name === "bn") && (ts.isStringLiteral(property.initializer) || ts.isNoSubstitutionTemplateLiteral(property.initializer))) {
          entry[name] = property.initializer.text.trim();
        }
      }
      catalogTranslations.set(node.name.text, entry);
    }
    ts.forEachChild(node, visit);
  };
  visit(tree);
}

const templateTranslations = new Map();
const templateFile = "lib/i18n-generated-templates.ts";
if (fs.existsSync(templateFile)) {
  const source = fs.readFileSync(templateFile, "utf8");
  const tree = ts.createSourceFile(templateFile, source, ts.ScriptTarget.Latest, true, ts.ScriptKind.TS);
  const visit = (node) => {
    if (ts.isObjectLiteralExpression(node)) {
      const entry = {};
      for (const property of node.properties) {
        if (!ts.isPropertyAssignment(property)) continue;
        const name = ts.isIdentifier(property.name) || ts.isStringLiteral(property.name) ? property.name.text : "";
        if ((name === "source" || name === "en" || name === "bn") && (ts.isStringLiteral(property.initializer) || ts.isNoSubstitutionTemplateLiteral(property.initializer))) {
          entry[name] = property.initializer.text.trim();
        }
      }
      if (entry.source && entry.en && entry.bn) templateTranslations.set(entry.source, entry);
    }
    ts.forEachChild(node, visit);
  };
  visit(tree);
}

function validTranslation(value, target, placeholders = []) {
  if (!value || /[ء-ي]/.test(value) || /[♪♫]|\. \. \.|_{4,}|DALI[\s_-]*VAR|&(?:apos|quot|amp|lt|gt|#\d+);|\(_?D\)|DOR_VAR|copertor/i.test(value)) return false;
  if (target === "en" ? !/[A-Za-z]/.test(value) : !/[\u0980-\u09ff]/.test(value)) return false;
  if (target === "bn" && [...value].some((character) => {
    const codepoint = character.codePointAt(0);
    return (codepoint >= 0x0370 && codepoint <= 0x052f)
      || (codepoint >= 0x0900 && codepoint <= 0x097f && codepoint !== 0x0964 && codepoint !== 0x0965);
  })) return false;
  return placeholders.every((placeholder) => value.includes(placeholder));
}

const terminologyRules = [
  { target: "en", source: /عامل/, forbidden: /\b(?:factor|agent)s?\b/i },
  { target: "en", source: /كفال|كفيل/, forbidden: /\b(?:bail|guarantee|surety|guarantor)\b/i },
  { target: "en", source: /عقد/, forbidden: /\bdecade\b/i },
  { target: "en", source: /وردي/, forbidden: /\b(?:pink|rose|roses)\b/i },
  { target: "en", source: /إقام/, forbidden: /\b(?:residence|accommodation)\b/i },
  { target: "en", source: /جار(?:ٍ|ي)/, forbidden: /\bneighbor\w*\b/i },
  { target: "en", source: /ترحيل/, forbidden: /\bdeportation\b/i },
  { target: "en", source: /مكة/, forbidden: /\bMecca\b/i },
  { target: "bn", source: /عامل/, forbidden: /ফ্যাক্টর/ },
  { target: "bn", source: /كفال|كفيل/, forbidden: /ওয়ারেন্টি|নিশ্চয়তা|জামিন|বেইল/ },
  { target: "bn", source: /إقام/, forbidden: /বাসস্থান/ },
  { target: "bn", source: /مكة/, forbidden: /মেক্সিকো|মেকা/ },
  { target: "bn", source: /جدة/, forbidden: /দাদা/ },
  { target: "bn", source: /حج/, forbidden: /নামাজ|প্রার্থনা/ },
  { target: "bn", source: /جار(?:ٍ|ي)/, forbidden: /প্রতিবেশী/ },
  { target: "bn", source: /مهن(?!ي)/, forbidden: /ক্যারিয়ার/ },
];

function validTerminology(source, value, target) {
  return !terminologyRules.some((rule) => rule.target === target && rule.source.test(source) && rule.forbidden.test(value));
}

function belongsToArea(files, area) {
  const publicLibraryFiles = new Set(["business-hours", "chat-automation", "construction-content", "insights", "service-catalog", "site-content", "site", "website-content"]);
  const isPublic = (file) => !file.startsWith("app/portal/") && (!file.startsWith("lib/") || publicLibraryFiles.has(path.basename(file, ".ts")));
  const isPortal = (file) => file.startsWith("app/portal/") || (file.startsWith("lib/") && !isPublic(file));
  return area === "portal"
    ? [...files].some(isPortal)
    : [...files].some(isPublic);
}

let missingCount = 0;
for (const area of ["public", "portal"]) {
  const staticRows = [...visibleStrings].filter(([, files]) => belongsToArea(files, area));
  const templateRows = [...visibleTemplates].filter(([, files]) => belongsToArea(files, area));
  const missing = { en: [], bn: [] };
  const missingTemplates = { en: [], bn: [] };
  for (const [value, files] of staticRows) {
    const entry = catalogTranslations.get(value) || {};
    for (const target of ["en", "bn"]) if (!validTranslation(entry[target], target) || !validTerminology(value, entry[target], target)) missing[target].push([value, files]);
  }
  for (const [value, files] of templateRows) {
    const entry = templateTranslations.get(value) || {};
    const placeholders = [...value.matchAll(/\{\{\d+\}\}/g)].map((match) => match[0]);
    for (const target of ["en", "bn"]) if (!validTranslation(entry[target], target, placeholders) || !validTerminology(value, entry[target], target)) missingTemplates[target].push([value, files]);
  }
  missingCount += missing.en.length + missing.bn.length + missingTemplates.en.length + missingTemplates.bn.length;
  console.log(JSON.stringify({
    area,
    visibleStrings: staticRows.length,
    visibleTemplates: templateRows.length,
    en: { translated: staticRows.length - missing.en.length, missing: missing.en.length, dynamicMissing: missingTemplates.en.length },
    bn: { translated: staticRows.length - missing.bn.length, missing: missing.bn.length, dynamicMissing: missingTemplates.bn.length },
    complete: !missing.en.length && !missing.bn.length && !missingTemplates.en.length && !missingTemplates.bn.length,
  }));
  if (process.argv.includes("--details")) {
    for (const target of ["en", "bn"]) {
      for (const [value, files] of missing[target].sort(([a], [b]) => a.localeCompare(b, "ar"))) console.log(`${area}\t${target}\tstatic\t${value}\t${[...files].join(",")}`);
      for (const [value, files] of missingTemplates[target].sort(([a], [b]) => a.localeCompare(b, "ar"))) console.log(`${area}\t${target}\ttemplate\t${value}\t${[...files].join(",")}`);
    }
  }
}

if (missingCount) {
  console.error(`Translation audit failed: ${missingCount} required translations are missing or invalid.`);
  process.exitCode = 1;
}
