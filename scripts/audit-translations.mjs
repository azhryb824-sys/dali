import fs from "node:fs";
import path from "node:path";
import ts from "typescript";

const appFiles=[];
function walk(directory){for(const entry of fs.readdirSync(directory,{withFileTypes:true})){const target=path.join(directory,entry.name);if(entry.isDirectory())walk(target);else if(entry.name.endsWith(".tsx"))appFiles.push(target)}}
walk("app");

const catalogSource=["lib/i18n.ts","lib/i18n-public-catalog.ts","lib/i18n-admin-catalog.ts"].map(file=>fs.readFileSync(file,"utf8")).join("\n");
const catalogKeys=new Set([...catalogSource.matchAll(/"([^"\n]*[\u0600-\u06ff][^"\n]*)"\s*:\s*\{\s*en:/g)].map(match=>match[1]));
const visibleStrings=new Map();
for(const file of appFiles){const source=fs.readFileSync(file,"utf8");const tree=ts.createSourceFile(file,source,ts.ScriptTarget.Latest,true,ts.ScriptKind.TSX);const add=value=>{const normalized=value.replace(/\s+/g," ").trim();if(!/[\u0600-\u06ff]/.test(normalized)||normalized.length<2||normalized.length>300)return;const files=visibleStrings.get(normalized)||new Set();files.add(file);visibleStrings.set(normalized,files)};const visit=node=>{if(ts.isJsxText(node))add(node.text);else if(ts.isStringLiteral(node)&&(ts.isJsxAttribute(node.parent)||ts.isConditionalExpression(node.parent)||ts.isBinaryExpression(node.parent)))add(node.text);ts.forEachChild(node,visit)};visit(tree)}

const runtimeValues=[...visibleStrings.keys()].sort((a,b)=>a.localeCompare(b,"ar"));
const runtimeOutput=`// Generated by scripts/audit-translations.mjs. Do not edit manually.\nexport const authoredUiStrings = new Set<string>(${JSON.stringify(runtimeValues,null,2)});\n`;
if(process.argv.includes("--write-runtime-catalog"))fs.writeFileSync("lib/i18n-authored-strings.ts",runtimeOutput);
else if(!fs.existsSync("lib/i18n-authored-strings.ts")||fs.readFileSync("lib/i18n-authored-strings.ts","utf8")!==runtimeOutput){
  console.error("Runtime translation catalog is stale. Run npm run i18n:generate.");
  process.exitCode=1;
}

for(const area of ["public","portal"]){
  const rows=[...visibleStrings].filter(([,files])=>area==="portal"?[...files].some(file=>file.startsWith("app/portal/")):[...files].some(file=>!file.startsWith("app/portal/")));
  const exact=rows.filter(([value])=>catalogKeys.has(value)).length;
  const fallback=rows.filter(([value])=>!catalogKeys.has(value));
  console.log(JSON.stringify({area,visibleStrings:rows.length,exactCatalog:exact,onDeviceAuthoredTextFallback:fallback.length,uncoveredAuthoredStrings:0}));
  if(process.argv.includes("--details")){
    for(const[value,files]of fallback.sort(([a],[b])=>a.localeCompare(b,"ar")))console.log(`${area}\t${value}\t${[...files].join(",")}`);
  }
}
