import test from 'node:test';
import assert from 'node:assert/strict';
import { readFile, mkdtemp, rm } from 'node:fs/promises';
import { resolve } from 'node:path';
import { pathToFileURL } from 'node:url';
import { build } from 'esbuild';
import { PGlite } from '@electric-sql/pglite';
import { drizzle } from 'drizzle-orm/pglite';
import { generateDrizzleJson, generateMigration } from 'drizzle-kit/api';

test('worker creation accepts both sponsorship types under the production database constraint', async () => {
 const directory = await mkdtemp(resolve('node_modules/.worker-creation-'));
 const pg = new PGlite();
 try {
  const outfile = resolve(directory, 'qa.mjs');
  await build({stdin:{contents:`export * as schema from './db/schema.ts'; export { POST } from './app/api/portal/workers/route.ts'; export { workforceNationalities, workforceProfessions } from './lib/workforce-requirements.ts'; export { saudiBanks } from './lib/saudi-banks.ts'; export {setDb, events, objects, failStorageAfter} from 'qa-state';`,resolveDir:process.cwd()},outfile,bundle:true,platform:'node',format:'esm',packages:'external',plugins:[{name:'isolate',setup(b){
   b.onResolve({filter:/^(qa-state|@\/db|@\/lib\/(portal-access|runtime-env|portal-notifications))$/},()=>({path:'state',namespace:'qa'}));
   b.onLoad({filter:/.*/,namespace:'qa'},()=>({contents:`let db; export function getSqlClient(){throw new Error('Unexpected SQL call')} export const events=[]; export const objects=new Map(); let remaining=Infinity; export const failStorageAfter=n=>remaining=n; export const setDb=v=>db=v; export const getDb=()=>db; export async function requirePortalApiRole(){return {role:'admin',user:{email:'qa@test.local'}}} export const canAccessPortalDepartment=()=>true; export const getRuntimeEnv=()=>({BUCKET:{async put(key,bytes){objects.set(key,bytes); if(--remaining<0) throw Object.assign(new Error("private storage details"),{code:"ENOSPC"})},async delete(key){objects.delete(key)}}}); export async function emitPortalNotification(event){events.push(event)}`}));
  }}]});
  const qa=await import(pathToFileURL(outfile).href);
  const statements=await generateMigration(generateDrizzleJson({}),generateDrizzleJson(qa.schema));
  for(const statement of statements) await pg.exec(statement);
  await pg.exec(await readFile('drizzle-pg/0021_worker_iban_insurance_and_attachment_expiry.sql','utf8'));
  const migration=await readFile('drizzle-pg/0032_sponsorship_and_ajir_consistency.sql','utf8');
  await pg.exec(migration);
  qa.setDb(drizzle(pg,{schema:qa.schema}));
  const forms=[];
  for(const [i,sponsorship] of ['dali','other'].entries()) {
   const form=new FormData();
   for(const [key,value] of Object.entries({workerNumber:`QA-${i}`,iqamaNumber:`200000000${i}`,fullName:'عامل اختبار',nationality:qa.workforceNationalities[0],profession:qa.workforceProfessions[0].label,mobile:'0501234567',iban:`SA038000000060801016751${i}`,bankName:qa.saudiBanks[0],monthlySalary:'2500',sponsorshipType:sponsorship,sponsorName:sponsorship==='other'?'جهة اختبار':'',iqamaExpiry:'2027-01-01',medicalInsuranceExpiry:'2027-01-01'})) form.set(key,value);
   for(const name of ['photo','iqamaDocument','ibanCertificate']) form.set(name,new File([new Uint8Array([137,80,78,71,13,10,26,10,0])],'test.png',{type:'image/png'}));
   forms.push(form);
   const response=await qa.POST(new Request('https://www.dally.info/api/portal/workers',{method:'POST',body:form}));
   const result=await response.json();
   assert.equal(response.status,201,JSON.stringify(result));
   assert.equal(result.attachments.length,3);
   assert.equal(result.worker.bankName,"مصرف الراجحي","bank is derived from IBAN, ignoring submitted bank name");
   assert.equal(result.worker.sponsorshipType,sponsorship);
   const duplicate=await qa.POST(new Request('https://www.dally.info/api/portal/workers',{method:'POST',body:form}));
   assert.equal(duplicate.status,409,JSON.stringify(await duplicate.json()));
  }
  const send=form=>qa.POST(new Request('https://www.dally.info/api/portal/workers',{method:'POST',body:form}));
  const form=forms[0];
  form.set('workerNumber','QA-UNIQUE');
  assert.equal((await send(form)).status,409,'duplicate iqama alone is reported correctly');
  form.set('iqamaNumber','2999999999');
  form.set('workerNumber','QA-1');
  assert.equal((await send(form)).status,409,'duplicate worker number alone is reported correctly');
  form.set('workerNumber','QA-FAILURE');
  const duplicateIban=await send(form);
  assert.equal(duplicateIban.status,409);
  assert.equal((await duplicateIban.json()).code,'DUPLICATE_WORKER_IBAN');
  form.set('iban','SA0380000000608010167599');
  const validPhoto=form.get('photo');
  form.set('photo',new File(['not a PNG'],'forged.png',{type:'image/png'}));
  const invalid=await send(form);
  assert.equal(invalid.status,400);
  assert.match((await invalid.json()).error,/صورة العامل/);
  assert.equal(qa.objects.size,6,'invalid file writes no objects');
  form.set('photo',new File([new Uint8Array(5*1024*1024+1)],'large.png',{type:'image/png'}));
  assert.equal((await send(form)).status,400,'oversized photo is a validation error');
  assert.equal(qa.objects.size,6);
  form.set('photo',validPhoto);
  qa.failStorageAfter(1);
  const storage=await send(form);
  assert.equal(storage.status,500);
  const storageBody=await storage.json();
  assert.match(storageBody.error,/المرفقات/);
  assert.ok(storageBody.referenceId);
  assert.doesNotMatch(JSON.stringify(storageBody),/private storage details|ENOSPC/);
  assert.equal(qa.objects.size,6,'partial uploads are cleaned up');
  qa.failStorageAfter(Infinity);
  await pg.exec(`CREATE FUNCTION qa_reject_activity() RETURNS trigger LANGUAGE plpgsql AS $$ BEGIN RAISE EXCEPTION 'private failure'; END $$; CREATE TRIGGER qa_reject_activity BEFORE INSERT ON portal_activity FOR EACH ROW EXECUTE FUNCTION qa_reject_activity();`);
  assert.equal((await send(form)).status,500,'activity failure aborts the creation transaction');
  assert.equal(qa.objects.size,6,'database failure cleans all new objects');
  assert.equal((await pg.query('select * from worker_attachments')).rows.length,6,'no orphan attachments');
  assert.equal((await pg.query('select * from workers')).rows.length,2);
  assert.equal((await pg.query('select * from portal_activity')).rows.length,2);
  assert.equal(qa.events.length,2);
 } finally {await pg.close();await rm(directory,{recursive:true,force:true});}
});
